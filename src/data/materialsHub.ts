export interface MaterialPropertyRatings {
  printability: number // 1 - 5
  strength: number
  flexibility: number
  heatResistance: number
  surfaceQuality: number
  impactResistance: number
}

export interface MaterialFamily {
  id: string
  slug: string
  name: string
  fullName: string
  tagline: string
  positioning: string
  shortDescription: string
  color: string // Tailwind color key, e.g., 'emerald', 'orange', 'blue', 'violet', 'amber', 'cyan', 'rose'
  badgeColor: string
  emoji: string
  difficulty: 'Beginner' | 'Intermediate' | 'Advanced'
  category: 'standard' | 'engineering' | 'flexible' | 'support' | 'carbon'
  categoryLabel: string
  properties: MaterialPropertyRatings
  propertyHighlights: {
    strengthText: string
    flexibilityText: string
    heatText: string
    impactText: string
    printabilityText: string
  }
  printTemp: string
  bedTemp: string
  enclosureRequired: boolean
  density: string
  tensileStrength?: string
  benefits: string[]
  applications: string[]
  bestFor: string[]
  visualTheme: 'standard' | 'flexible' | 'support' | 'carbon'
  supportWorkflow?: {
    primaryMaterial: string
    solvent: string
    process: string
  }
}

